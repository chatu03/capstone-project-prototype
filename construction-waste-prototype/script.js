$("prediction-form").addEventListener("submit", (event) => {
  event.preventDefault();
  const project = state.projects.find((p) => p.id === $("prediction-project").value);
  const stage = $("prediction-stage").value;
  const material = $("prediction-material").value;
  const planned = Number($("prediction-quantity").value);
  if (!project) { notify("Add a project before creating a simulation.", true); return; }
  if (!MATERIALS[material] || !MATERIALS[material].stages.includes(stage)) { notify("Choose a material applicable to this stage.", true); return; }
  if (!Number.isFinite(planned) || planned <= 0 || planned > 1e9 || (MATERIALS[material].whole && !Number.isInteger(planned)) || Math.abs(planned * 100 - Math.round(planned * 100)) > .00001) {
    notify("Enter a positive quantity up to 1,000,000,000, using whole pieces or up to two decimal places for other units.", true); return;
  }
  const record = makeRecord(project, stage, material, planned);
  state.predictions.push(record);
  lastPredictionId = record.id;
  saveFeedback("Simulation complete.");
  renderAll();
  $("prediction-result").scrollIntoView({ block: "nearest" });
});
