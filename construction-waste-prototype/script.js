// localStorage handling: seed once, preserve intentionally empty lists, and keep
// the current session usable if the browser blocks storage (including file://).
function validData(data) {
  if (!data || data.version !== 1 || !Array.isArray(data.projects) || !Array.isArray(data.predictions)) return false;
  const validText = (value) => typeof value === "string" && value.trim().length > 0;
  return data.projects.every((p) => p && validText(p.id) && validText(p.name) && validText(p.location) && STAGES.includes(p.stage) && Number.isFinite(p.area) && p.area > 0)
    && data.predictions.every((r) => r && validText(r.id) && validText(r.projectId) && validText(r.projectName) && validText(r.location) && Object.hasOwn(MATERIALS, r.material) && MATERIALS[r.material].stages.includes(r.stage) && Number.isFinite(r.planned) && r.planned > 0 && r.planned <= 1e9 && Number.isFinite(r.waste) && r.waste >= 0 && r.waste <= r.planned && Number.isFinite(r.usable) && r.usable >= 0 && Math.abs(r.usable + r.waste - r.planned) < .001 && Number.isFinite(r.rate) && r.rate >= 0 && r.rate <= 100 && Number.isFinite(new Date(r.date).getTime()) && (!MATERIALS[r.material].whole || (Number.isInteger(r.planned) && Number.isInteger(r.waste) && Number.isInteger(r.usable))));
}
function loadData() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved !== null) {
      const data = JSON.parse(saved);
      if (!validData(data)) throw new Error("Invalid saved data");
      return data;
    }
    const data = sampleData();
    localStorage.setItem(STORAGE_KEY, JSON.stringify(data));
    return data;
  } catch (error) {
    storageAvailable = false;
    notify("Saved data could not be loaded. Using temporary demonstration data; existing storage has not been overwritten. Enable browser storage or reset data to retry.", true);
    return sampleData();
  }
}
let state = loadData();
function saveData() {
  try {
    // Do not overwrite unreadable data without an explicit reset.
    if (!storageAvailable) return false;
    localStorage.setItem(STORAGE_KEY, JSON.stringify(state));
    return true;
  } catch (error) {
    storageAvailable = false;
    return false;
  }
}
function saveFeedback(message) {
  const saved = saveData();
  notify(saved ? `${message} Saved on this browser.` : `${message} Session only: browser storage is unavailable. Changes will be lost on reload.`, !saved);
}

