function deleteProject(id) {
  const project = state.projects.find((p) => p.id === id);
  if (!project || !window.confirm(`Delete “${project.name}”? Saved simulation reports will be retained with their original project details.`)) return;
  state.projects = state.projects.filter((p) => p.id !== id);
  if ($("project-id").value === id) $("project-form").hidden = true;
  saveFeedback("Project deleted. Existing simulation reports were retained.");
  renderAll();
}

