function syncProjectStage() {
  const project = state.projects.find((p) => p.id === $("prediction-project").value);
  if (project) $("prediction-stage").value = project.stage;
  filterMaterials();
}
function filterMaterials() {
  const stage = $("prediction-stage").value;
  const previous = $("prediction-material").value;
  // On roofing, prioritise roofing sheets before timber.
  const applicable = Object.keys(MATERIALS).filter((key) => MATERIALS[key].stages.includes(stage));
  if (stage === "Roofing") applicable.sort((a) => a === "roofing" ? -1 : 1);
  $("prediction-material").innerHTML = applicable.map((key) => `<option value="${key}">${MATERIALS[key].name}</option>`).join("");
  if (applicable.includes(previous) && stage !== "Roofing") $("prediction-material").value = previous;
  updateUnit();
}
function updateUnit() {
  const key = $("prediction-material").value;
  const material = MATERIALS[key];
  if (!material) return;
  $("prediction-unit").textContent = material.unit;
  $("prediction-quantity").step = material.whole ? "1" : "0.01";
  $("prediction-quantity").min = material.whole ? "1" : "0.01";
  $("quantity-hint").textContent = material.whole ? "Enter whole pieces only. Waste is rounded to the nearest piece." : "Enter a positive quantity with up to two decimal places.";
  $("rate-note").textContent = `Illustrative waste rate: ${WASTE_RATES[key]}%. This is a fictional demonstration assumption, not an established construction waste rate.`;
  $("prediction-quantity").setCustomValidity("");
}
