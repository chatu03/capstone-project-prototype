document.addEventListener("click", (event) => {
  const button = event.target.closest("button");
  if (!button) return;
  if (button.dataset.editProject) openProjectForm(button.dataset.editProject);
  if (button.dataset.deleteProject) deleteProject(button.dataset.deleteProject);
  if (button.dataset.report) openReport(button.dataset.report);
  if (button.dataset.predictProject) {
    $("prediction-project").value = button.dataset.predictProject;
    syncProjectStage();
    showPage("prediction");
  }
  const action = button.dataset.action;
  if (action === "add-project") openProjectForm();
  if (action === "new-prediction") showPage("prediction");
  if (["projects", "reports", "recommendations"].includes(action)) showPage(action);
});
