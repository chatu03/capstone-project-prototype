    const percentage = total.waste / total.planned * 100;
    return `<div class="chart-row"><span class="chart-name">${MATERIALS[material].name}</span><div class="chart-track" role="img" aria-label="${escapeHTML(MATERIALS[material].name)}: ${quantity(total.waste, material)} simulated waste, ${number(percentage)}% of planned quantity"><div class="chart-fill" style="width:${percentage}%"></div></div><span class="chart-value">${quantity(total.waste, material)}</span></div>`;
