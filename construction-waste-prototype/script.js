function uniqueId(prefix) {
  return `${prefix}-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;
}

// Simulated waste calculations: round pieces to whole numbers; retain two decimals
// for bags, kg and m³. Usable + waste always equals the entered quantity.
function calculateWaste(material, planned) {
  const rate = WASTE_RATES[material];
  const waste = MATERIALS[material].whole ? Math.round(planned * rate / 100) : Math.round(planned * rate) / 100;
  const usable = Math.round((planned - waste) * 100) / 100;
  return { waste, usable, rate, actualPercent: waste / planned * 100 };
}
function makeRecord(project, stage, material, planned, sample = false) {
  return {
    id: uniqueId("simulation"), projectId: project.id, projectName: project.name,
    location: project.location, stage, material, planned,
    ...calculateWaste(material, planned), date: new Date().toISOString(), sample
  };
}
